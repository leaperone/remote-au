#Requires -Version 5.1
<#
.SYNOPSIS
  Per-user install: copy/locate remote-au binary, config dir, logon Scheduled Task (no password).
.NOTES
  CLI flags follow Rust core handoff (remote-au send). Does not install virtual audio drivers.
#>
[CmdletBinding()]
param(
    [string] $BinarySource,
    [string] $Receiver,
    [ValidateSet('send', 'server')]
    [string] $Role = 'send',
    [switch] $SkipFirewallHint
)

$ErrorActionPreference = 'Stop'

$AppName = 'remote-au'
$Root = Join-Path $env:LOCALAPPDATA $AppName
$BinDir = Join-Path $Root 'bin'
$ConfigDir = Join-Path $Root 'config'
$LogDir = Join-Path $Root 'logs'
$Exe = Join-Path $BinDir 'remote-au.exe'
$Wrapper = Join-Path $Root 'run-daemon.ps1'
$EnvFile = Join-Path $Root 'daemon-env.ps1'
$TaskName = "$AppName-daemon"

function Ensure-Directory([string] $Path) {
    if (-not (Test-Path -LiteralPath $Path)) {
        New-Item -ItemType Directory -Path $Path -Force | Out-Null
    }
}

function Set-AppTreeAcl([string] $Path) {
    if (-not (Test-Path -LiteralPath $Path)) { return }
    $acl = Get-Acl -LiteralPath $Path
    $acl.SetAccessRuleProtection($true, $false)
    $user = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
    $system = [System.Security.Principal.SecurityIdentifier]::new('S-1-5-18')
    $rules = @(
        [System.Security.AccessControl.FileSystemAccessRule]::new(
            $user, 'FullControl', 'ContainerInherit,ObjectInherit', 'None', 'Allow'),
        [System.Security.AccessControl.FileSystemAccessRule]::new(
            $system, 'FullControl', 'ContainerInherit,ObjectInherit', 'None', 'Allow')
    )
    foreach ($r in $rules) { $acl.AddAccessRule($r) }
    Set-Acl -LiteralPath $Path -AclObject $acl
}

function Test-ReceiverAddress([string] $Addr) {
    if ([string]::IsNullOrWhiteSpace($Addr)) { return $true }
    if ($Addr -notmatch '^[A-Za-z0-9.\-]+:\d{1,5}$') {
        throw "Invalid -Receiver '$Addr' (expected host:port, no spaces or shell metacharacters)"
    }
    $port = [int]($Addr.Split(':')[-1])
    if ($port -lt 1 -or $port -gt 65535) {
        throw "Invalid receiver port in '$Addr'"
    }
}

function Stop-DaemonTaskAndWait([string] $Name, [string] $ExePath) {
    $task = Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
    if (-not $task) { return }
    try {
        Stop-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue | Out-Null
    } catch { }
    for ($i = 0; $i -lt 45; $i++) {
        $state = (Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue).State
        if ($state -ne 'Running') { break }
        Start-Sleep -Seconds 1
    }
    Get-Process -Name 'remote-au' -ErrorAction SilentlyContinue | ForEach-Object {
        if ($ExePath -and $_.Path -eq $ExePath) {
            Stop-Process -Id $_.Id -Force -ErrorAction SilentlyContinue
        }
    }
    Start-Sleep -Seconds 1
}

function Write-DaemonEnvFile(
    [string] $Path,
    [string] $ExePath,
    [string] $Config,
    [string] $Log,
    [string] $Recv,
    [string] $DaemonRole
) {
    $lines = @(
        "# Generated by install-daemon.ps1 — do not edit",
        "`$RemoteAuExe = '$($ExePath.Replace("'", "''"))'",
        "`$RemoteAuConfigDir = '$($Config.Replace("'", "''"))'",
        "`$RemoteAuLogFile = '$($Log.Replace("'", "''"))'",
        "`$RemoteAuRole = '$DaemonRole'",
        "`$RemoteAuReceiver = '$($Recv.Replace("'", "''"))'"
    )
    Set-Content -LiteralPath $Path -Value ($lines -join "`n") -Encoding UTF8
}

$recv = $Receiver
if (-not $recv -and $env:REMOTE_AU_TO) { $recv = $env:REMOTE_AU_TO }
Test-ReceiverAddress $recv

$createdRoot = -not (Test-Path -LiteralPath $Root)
Ensure-Directory $BinDir
Ensure-Directory $ConfigDir
Ensure-Directory $LogDir
if ($createdRoot) {
    Set-AppTreeAcl $Root
}
Set-AppTreeAcl $ConfigDir

Stop-DaemonTaskAndWait -Name $TaskName -ExePath $Exe

if ($BinarySource) {
    if (-not (Test-Path -LiteralPath $BinarySource)) {
        throw "BinarySource not found: $BinarySource"
    }
    Copy-Item -LiteralPath $BinarySource -Destination $Exe -Force
} elseif (-not (Test-Path -LiteralPath $Exe)) {
    throw "Place remote-au.exe at '$Exe' or pass -BinarySource. (Rust build not bundled here.)"
}

$LogFile = Join-Path $LogDir 'daemon.log'
$installScript = Join-Path $PSScriptRoot 'run-daemon.ps1'
if (-not (Test-Path -LiteralPath $installScript)) {
    throw "Missing wrapper script: $installScript"
}
Copy-Item -LiteralPath $installScript -Destination $Wrapper -Force
Write-DaemonEnvFile -Path $EnvFile -ExePath $Exe -Config $ConfigDir -Log $LogFile -Recv $(if ($recv) { $recv } else { '' }) -DaemonRole $Role

$existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($existing) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}

$wrapperQuoted = '"' + $Wrapper + '"'
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File $wrapperQuoted"
$trigger = New-ScheduledTaskTrigger -AtLogOn -User ([System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value)
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew `
    -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit ([TimeSpan]::Zero)
$sid = [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value
$principal = New-ScheduledTaskPrincipal -UserId $sid -LogonType Interactive -RunLevel Limited

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null

Write-Host "Installed $Role task '$TaskName' -> $Exe"
Write-Host "Config: $ConfigDir (pairing preserved on uninstall unless -Purge)"
Write-Host "Logs: $LogFile (wrapper rotates above 5MB before each run)"
if ($recv) {
    Write-Host "Receiver: $recv (pinned via -Receiver / REMOTE_AU_TO)"
} else {
    Write-Host "Receiver: auto discovery (omit --to); pin with -Receiver host:port"
}

$pairingFile = Join-Path $ConfigDir 'pairing.json'
if (Test-Path -LiteralPath $pairingFile) {
    Start-ScheduledTask -TaskName $TaskName
    Write-Host "pairing.json found; started scheduled task."
} else {
    Write-Host ""
    Write-Host "Not paired yet. On the receiver, create an invitation; then on this PC:"
    Write-Host "  & '$($Exe.Replace("'", "''"))' --config-dir '$($ConfigDir.Replace("'", "''"))' pair --import-file <path-to-invitation>"
    Write-Host "When pairing.json exists:"
    Write-Host "  Start-ScheduledTask -TaskName '$TaskName'"
}

Write-Host ""
Write-Host "Manual task control: scripts\windows\daemon-task-commands.ps1"

if (-not $SkipFirewallHint) {
    Write-Host ""
    Write-Host "Optional (admin): scripts\windows\add-firewall-rules.ps1 -ProgramPath '$Exe'"
    Write-Host "Receiver role on Windows: run server manually; uninstall rules via uninstall-firewall-rules.ps1"
}
